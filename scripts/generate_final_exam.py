def new_doc_from_template(template_path: Path):
  path = Path(tempfile.mktemp(suffix=".docx"))
  shutil.copy(template_path, path)
  doc = Document(path)
  body = doc.element.body
  for child in list(body):
    if child.tag.endswith("p"):
      body.remove(child)
  return doc, path


def set_run_font(run, font="宋体", size=None, bold=False):
  run.font.name = font
  run.font.bold = bold
  run._element.rPr.rFonts.set(qn("w:eastAsia"), font)
  if size is not None:
    run.font.size = Pt(size)


def add_p(
    doc,
    text,
    *,
    align=WD_ALIGN_PARAGRAPH.LEFT,
    font="宋体",
    size=None,
    bold=False,
    indent=None,
):
  p = doc.add_paragraph()
  p.alignment = align
  pf = p.paragraph_format
  pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
  if indent:
    pf.first_line_indent = Cm(indent)
  r = p.add_run(text)
  set_run_font(r, font, size, bold)
  return p


def add_lines(doc, lines, *, align=WD_ALIGN_PARAGRAPH.LEFT, font="宋体", indent=None):
  for line in lines:
    add_p(doc, line, align=align, font=font, indent=indent)


def add_poem(doc, title, author, poem_lines):
  add_p(doc, "【甲】", align=WD_ALIGN_PARAGRAPH.JUSTIFY)
  add_p(doc, title, align=WD_ALIGN_PARAGRAPH.CENTER, font="楷体")
  add_p(doc, author, align=WD_ALIGN_PARAGRAPH.CENTER, font="楷体")
  for line in poem_lines:
    add_p(doc, line, align=WD_ALIGN_PARAGRAPH.CENTER, font="楷体")


def add_poem_yi(doc, title, author, poem_lines):
  add_p(doc, "【乙】", align=WD_ALIGN_PARAGRAPH.JUSTIFY)
  add_p(doc, title, align=WD_ALIGN_PARAGRAPH.CENTER, font="楷体")
  add_p(doc, author, align=WD_ALIGN_PARAGRAPH.CENTER, font="楷体")
  for line in poem_lines:
    add_p(doc, line, align=WD_ALIGN_PARAGRAPH.CENTER, font="楷体")


def add_classical(doc, label, text, source):
  add_p(doc, label, align=WD_ALIGN_PARAGRAPH.JUSTIFY)
  add_p(doc, text)
  add_p(doc, source, align=WD_ALIGN_PARAGRAPH.RIGHT)


def add_article(doc, title, author, paragraphs, source):
  add_p(doc, title, align=WD_ALIGN_PARAGRAPH.CENTER)
  if author:
    add_p(doc, author, align=WD_ALIGN_PARAGRAPH.CENTER)
  for para in paragraphs:
    add_p(doc, para)
  add_p(doc, source, align=WD_ALIGN_PARAGRAPH.RIGHT)


def add_section(doc, text):
  add_p(doc, text, bold=True, size=12)


def add_subsection(doc, text):
  add_p(doc, text, bold=True, size=12)


def add_choice_options(doc, options):
  for opt in options:
    add_p(doc, opt)


def add_ans_block(doc, answer, analysis=None, details=None):
  add_p(doc, f"【答案】{answer}")
  if analysis is not None:
    add_p(doc, "【解析】")
    if analysis:
      add_p(doc, analysis)
  if details:
    for title, body in details:
      add_p(doc, title)
      if body:
        add_p(doc, body)


