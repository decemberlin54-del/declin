def build_homework_design():
  doc = Document()
  sec = doc.sections[0]
  sec.page_width = Cm(21)
  sec.page_height = Cm(29.7)
  sec.left_margin = Cm(2.5)
  sec.right_margin = Cm(2.5)

  def para(text, bold=False, center=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    r = p.add_run(text)
    r.font.name = "宋体"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    r.font.bold = bold

  para("七年级上册第六单元单元作业设计", bold=True, center=True)
  para("")
  para("【单元主题】想象与真实", bold=True)
  para("【母题链】自由与规则 → 真实与虚假 → 创造与生命 → 智慧与局限", bold=True)
  para("【大任务】“想象力博物馆”微展览", bold=True)
  para("")
  para("一、设计依据", bold=True)
  para(
      "本作业依据第六单元学历案（融合版）设计，题型、分值、版式对标2025年云南省中考语文真题。"
      "阅读材料兼顾课内篇目与课外拓展，课外现代文均不少于1200字，并注明可核查来源。"
  )
  para("")
  para("二、作业目标与学历案对应", bold=True)
  tbl = doc.add_table(rows=9, cols=3)
  tbl.style = "Table Grid"
  for i, h in enumerate(["题号", "对应学历案目标", "题型"]):
    tbl.rows[0].cells[i].text = h
  rows = [
    ("1—6", "积累语言；默写本单元名句", "选择、排序、默写"),
    ("7—8", "为“想象力博物馆”提炼策展主题", "综合性学习"),
    ("9—10", "比较不同文体想象；关联名著", "名著阅读"),
    ("11—12", "诗歌鉴赏与比较", "诗歌"),
    ("13—16", "文言实词、翻译、寓意", "文言文"),
    ("17—19", "说明文筛选与比较", "说明文"),
    ("20—23", "记叙文赏析与探究", "记叙文"),
    ("24—25", "联想想象创意表达", "写作"),
  ]
  for ri, row in enumerate(rows, 1):
    for ci, val in enumerate(row):
      tbl.rows[ri].cells[ci].text = val
  para("")
  para("三、阅读材料来源", bold=True)
  para("课内：《天上的街市》《穿井得一人》《杞人忧天》《皇帝的新装》等（七上第六单元）")
  para("课外文言文：《晋书·乐广传》（杯弓蛇影），中华书局点校本")
  para("课外说明文：鲁迅《中国小说的史的变迁》、袁珂《中国神话传说》、刘慈欣创作谈等，有删改")
  para("课外记叙文：安徒生童话及课内《皇帝的新装》，有删改")
  para("")
  para("四、学后反思", bold=True)
